
CREATE OR REPLACE FUNCTION абоненты_с_задолженностью(
    начало_периода date,
    количество_месяцев int4
)

RETURNS TABLE (
    абонент text,
    месяцев_оплачено int4,
    дата_последнего_платежа date,
    сумма_последнего_платежа int4
)

LANGUAGE sql
AS $$
    WITH абоненты AS (
        SELECT
            id,
            фио AS имя,
            'физ' AS тип
        FROM физические_лица

        UNION ALL

        SELECT
            id,
            наименование AS имя,
            'юр' AS тип
        FROM юридические_лица
    )
    SELECT
        а.имя AS абонент,
        п.месяцев_оплачено,
        п.дата_последнего_платежа,
        п.сумма_последнего_платежа
    FROM абоненты а
    LEFT JOIN LATERAL (
        SELECT
            COUNT(DISTINCT date_trunc('month', пл.дата))::int4
                AS месяцев_оплачено,

            MAX(пл.дата) AS дата_последнего_платежа,

            (ARRAY_AGG(пл.сумма ORDER BY пл.дата DESC))[1]
                AS сумма_последнего_платежа

        FROM платежи пл
        WHERE (
            (а.тип = 'физ' AND пл.физическое_лицо = а.id)
            OR
            (а.тип = 'юр' AND пл.юридическое_лицо = а.id)
        )
        AND пл.дата >= начало_периода
        AND пл.дата < начало_периода
            + количество_месяцев * INTERVAL '1 month'
    ) п ON TRUE
    WHERE п.месяцев_оплачено < количество_месяцев;
$$;
